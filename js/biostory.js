/* ================= Искорки: копилка для историй =================
   Заработано — лучший сбор искорок в каждой пройденной главе (переигрывание не даёт фармить).
   progress: {best:{chId:n}, spent:n, stories:[id]} */
function sparkStats(){
  const p = readProgress(), best = p.best || {};
  let fix = false; // главы, пройденные до этой версии: засчитываем 70% искорок главы
  for (const c of CHAPTERS) if (chapterDone(c.id) && best[c.id] === undefined){ const i = CHAPTERS.indexOf(c); best[c.id] = Math.round(newState(i).W.drops.length*.7); fix = true; }
  if (fix){ p.best = best; store.set(PKEY, JSON.stringify(p)); }
  const earned = Object.values(best).reduce((a, b) => a + b, 0), spent = p.spent || 0;
  return {earned, spent, left:Math.max(0, earned - spent), owned:p.stories || []};
}
function buyStory(id){
  const st = sparkStats(); if (st.left < STORY_COST || st.owned.includes(id)) return false;
  const p = readProgress(); p.spent = (p.spent || 0) + STORY_COST; p.stories = [...(p.stories || []), id]; store.set(PKEY, JSON.stringify(p));
  return true;
}

