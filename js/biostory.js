function storyDef(b){
  const s = BIO_STORY[b.id], first = s.lines.findIndex(l => l.m === undefined);
  const lines = s.lines.map((l, i) => i === first ? {...l, music:s.mood} : l);
  return {title:b.name, noJournal:true, left:'aya', right:s.right, music:'title', lines, story:s, bio:b, end(){ finishStory(b); }};
}
function playStory(b){
  hideScreens(); S.bioPlay = true; S.mode = 'play'; S.fadeIn = .6;
  startScene('story:' + b.id, storyDef(b));
}
function finishStory(b){
  S.bioPlay = false; showMenu(); renderChars(); showScreen('chars'); openBio(b);
}
// Кадр сцены знакомства: воспоминание или крыша в наши дни
function drawStory(){
  const sc = S.scene; if (!sc) return;
  const L = sc.lines[sc.i] || {}, mems = sc.def.story.mem;
  if (L.m !== undefined){
    if (sc.memNow !== L.m){ sc.memPrev = sc.memNow; sc.memNow = L.m; sc.memT = 0; }
    sc.memT = (sc.memT || 0) + 1/60;
    inBaseFrame(() => { drawMemory(mems[L.m]); if (sc.memPrev !== undefined && sc.memPrev !== null && sc.memT < .8){ ctx.save(); ctx.globalAlpha = 1 - sc.memT/.8; drawMemory(mems[sc.memPrev]); ctx.restore(); } });
    return;
  }
  if (sc.memNow !== null){ sc.memNow = null; sc.memPrev = null; sc.backT = 0; }
  sc.backT = (sc.backT || 0) + 1/60;
  drawMenuScene(true);
  renderVN();
  if (sc.backT < .8){ ctx.fillStyle = `rgba(30,18,10,${1 - sc.backT/.8})`; ctx.fillRect(0, 0, VW, VH); }
}
