// пройдена ли глава (по id)
function chapterDone(id){
  const i = CHAPTERS.findIndex(c => c.id === id); if (i < 0) return false;
  const p = readProgress();
  if ((p.done || []).includes(id) || i < p.unlocked) return true;
  return id === 'ch3' && !!Journal.data.scenes['ch3:beacon']; // прошли главу 3 в старой версии, где она была последней
}
function bioState(b){
  if (b.unlock && chapterDone(b.unlock)) return {open:true};
  const tz = (b.teaser || []).filter(([ch]) => chapterDone(ch)).pop();
  if (tz) return {open:false, met:true, name:tz[1], text:tz[2]};
  return {open:false, met:false};
}
// портрет на маленьком холсте; locked — тёмный силуэт
function drawBioPortrait(cv, who, mode, locked){
  const dpr = 2, w = cv.width = cv.clientWidth*dpr || 240, h = cv.height = cv.clientHeight*dpr || 240, c = cv.getContext('2d');
  c.clearRect(0, 0, w, h);
  if (who === 'iskra'){ drawIskra(c, w/2, h*.52, 1, (mode === 'head' ? 5.2 : 6.5)*w/240, 0, 1); }
  else if (VN_DRAW[who]){
    const s = (mode === 'head' ? .5 : .62)*w/240;
    c.save(); c.translate(w/2 - 4*s, mode === 'head' ? h*.5 + 290*s : h + 6*s - 20*s); c.scale(s, s);
    VN_DRAW[who](c, {t:1, emo:'', talk:false, blink:false}); c.restore();
  }
  if (locked){ c.save(); c.globalCompositeOperation = 'source-atop'; c.fillStyle = 'rgba(14,12,26,.94)'; c.fillRect(0, 0, w, h); c.restore(); }
}
function renderChars(){
  const list = $('charList'), info = $('charInfo'); list.innerHTML = ''; list.hidden = false; info.hidden = true;
  $('charSparks').textContent = `✦ Искорки: ${sparkStats().left}`;
  for (const b of BIOS){
    const st = bioState(b), card = document.createElement('button');
    card.className = 'charcard' + (st.open ? '' : ' locked');
    const name = st.open ? b.name : st.met ? st.name : '???';
    card.innerHTML = `<canvas></canvas><b>${name}</b><small>${st.open ? b.role : st.met ? 'Таинственный незнакомец' : 'Ещё не встречались'}</small>`;
    list.appendChild(card);
    drawBioPortrait(card.querySelector('canvas'), b.who, 'head', !st.open);
    card.addEventListener('click', () => openBio(b));
  }
}
function openBio(b){
  const st = bioState(b), info = $('charInfo');
  $('charList').hidden = true; info.hidden = false;
  const facts = st.open ? b.facts.filter(([ch]) => chapterDone(ch)).map(f => f[1]) : [];
  const name = st.open ? b.name : st.met ? st.name : '???';
  const meta = st.open ? [b.role, b.age].filter(Boolean).join(' · ') : '';
  const body = st.open ? `<ul>${facts.map(f => `<li>${f}</li>`).join('')}</ul>`
    : st.met ? `<p class="bioteaser">${st.text}</p><p class="biolock">🔒 Он не из тех, кто спешит делиться прошлым. Подробности откроются по мере развития истории.</p>`
    : `<p class="biolock">🔒 Вы ещё не встречались. Продолжайте путешествие, чтобы узнать, кто это.</p>`;
  info.innerHTML = `<canvas class="bioportrait"></canvas><div class="biotext"><h3>${name}</h3>${meta ? `<p class="biometa">${meta}</p>` : ''}${st.open && b.quote ? `<p class="bioquote">«${b.quote}»</p>` : ''}${st.open && BIO_STORY[b.id] ? `<p class="bioabout">${BIO_STORY[b.id].about}</p>` : ''}${body}${st.open ? storyBlock(b) : ''}</div>`;
  drawBioPortrait(info.querySelector('canvas'), b.who, 'bust', !st.open);
  const buy = $('bioBuy'), play = $('bioPlay');
  if (buy) buy.addEventListener('click', () => askConfirm(`Открыть историю «${b.name}» за ${STORY_COST} искорок?`, 'Открыть', () => { if (buyStory(b.id)){ sfx.unlock(); playStory(b); } }, 'chars'));
  if (play) play.addEventListener('click', () => playStory(b));
  sfx.blip();
}
// Полная история: открыта — текст и повтор сцены; закрыта — покупка за искорки
function storyBlock(b){
  const s = BIO_STORY[b.id];
  if (!s) return `<div class="biostory"><p class="biolock">🔒 История этого персонажа откроется позже.</p></div>`;
  const st = sparkStats();
  if (st.owned.includes(b.id)) return `<div class="biostory"><p class="biostoryh">История</p><p class="biostorytext">${s.story}</p><button class="mbtn primary" id="bioPlay"><span>▶ Смотреть знакомство</span></button></div>`;
  const need = STORY_COST - st.left;
  return `<div class="biostory"><p class="biostoryh">🔒 История и сцена знакомства</p>
    <button class="mbtn primary" id="bioBuy" ${need > 0 ? 'disabled' : ''}><span>Открыть за ${STORY_COST} ✦</span></button>
    <small class="biostorynote">${need > 0 ? `Не хватает ${need} ✦ — собирай искорки на уровнях` : `У тебя ${st.left} ✦`}</small></div>`;
}
